import { describe, expect, it } from "vitest";
import { checkHygiene } from "../src/index.ts";

const violationsIn = (path: string, content: string) =>
  checkHygiene([{ path, content }]).map(({ line, message }) => ({ line, message }));

describe("checkHygiene", () => {
  it("[FR-DP-7] accepts clean code and docs", () => {
    expect(violationsIn("packages/a/src/a.ts", "export const a = 1;\n")).toEqual([]);
    expect(violationsIn("docs/a.md", "Any TODO here is prose.\n")).toEqual([]);
  });

  it.each([
    ["apps/web/src/app/globals.css", "  margin: 12px;"],
    ["apps/web/src/app/page.tsx", '<p className="mt-[3px]">'],
    ["apps/web/src/app/page.tsx", '<p style={{ width: "1.5px" }}>'],
  ])("[NFR-10] rejects px in %s: %s", (path, line) => {
    expect(violationsIn(path, line)).toEqual([{ line: 1, message: "px unit in app styles" }]);
  });

  it.each([
    ["apps/web/src/app/globals.css", "  color: #fff;"],
    ["apps/web/src/app/globals.css", "  background: #7364db;"],
    ["apps/web/src/app/page.tsx", '<p style={{ color: "rgb(0, 0, 0)" }}>'],
    ["apps/web/src/app/page.tsx", '<p className="bg-[oklch(0.5_0.1_200)]">'],
  ])("[FR-WB-13] rejects a raw colour in %s: %s", (path, line) => {
    expect(violationsIn(path, line)).toEqual([{ line: 1, message: "raw colour in app styles" }]);
  });

  it.each([
    ["apps/web/src/app/globals.css", "  margin: 0.75rem;"],
    ["apps/web/src/app/page.tsx", '<a href="#main" className="h-px">'],
    ["apps/web/src/app/globals.css", "/* the design shows 12px and #fff */"],
    ["apps/web/src/generated/tokens.css", "  --surface: #ffffff;"],
    ["apps/web/test/page.test.tsx", 'expect(width).toBe("12px");'],
    ["packages/design-tokens/src/themes.ts", 'canvas: "#f5f5fa",'],
  ])("[NFR-10] allows %s: %s", (path, line) => {
    expect(violationsIn(path, line)).toEqual([]);
  });

  it.each(["it.only(", "describe.only(", "test.skip(", "it.skip("])(
    "[FR-DP-7] rejects %s in a test file",
    (call) => {
      expect(violationsIn("packages/a/test/a.test.ts", `\n${call}"a", run);`)).toEqual([
        { line: 2, message: "focused or skipped test" },
      ]);
    },
  );

  it.each(["test/a.ts", "packages/a/test/helper.ts", "src/a.test.ts", "src/a.test.tsx"])(
    "[FR-DP-7] treats %s as a test file",
    (path) => {
      expect(violationsIn(path, "it.only(")).toHaveLength(1);
    },
  );

  it.each(["src/test.ts", "src/latest/a.ts", "src/a.test.ts.md", "src/attest/a.ts"])(
    "[FR-DP-7] does not treat %s as a test file",
    (path) => {
      expect(violationsIn(path, "it.only(")).toEqual([]);
    },
  );

  it("[FR-DP-7] allows the same words outside test files", () => {
    expect(violationsIn("packages/a/src/a.ts", "const it = { only: 1 }; it.only;")).toEqual([]);
  });

  it.each(["const a: any = 1;", "run(b as any);", "new Set<any>();"])(
    "[FR-DP-7] rejects the any type in %s",
    (code) => {
      expect(violationsIn("packages/a/src/a.ts", code)).toEqual([
        { line: 1, message: "the any type" },
      ]);
    },
  );

  it.each(["// matches as any other", " * as any other", "/* as any other */"])(
    "[FR-DP-7] ignores the word any in the comment %s",
    (comment) => {
      expect(violationsIn("packages/a/src/a.ts", comment)).toEqual([]);
    },
  );

  it("[FR-DP-7] requires a reason on lint disables", () => {
    expect(violationsIn("a.ts", "// eslint-disable-next-line no-console")).toEqual([
      { line: 1, message: "lint disable without a reason" },
    ]);
    expect(violationsIn("a.ts", "// eslint-disable-next-line no-console -- CLI output")).toEqual(
      [],
    );
  });

  it("[FR-DP-7] requires an issue on TODO and FIXME", () => {
    expect(violationsIn("a.ts", "// TODO: later\n// FIXME later")).toEqual([
      { line: 1, message: "TODO without an issue" },
      { line: 2, message: "TODO without an issue" },
    ]);
    expect(violationsIn("a.ts", "// TODO(#12): later")).toEqual([]);
  });

  it.each(["/* v8 ignore next */", "/* c8 ignore start */", "/* istanbul ignore next */"])(
    "[FR-DP-7] rejects the coverage exclusion %s",
    (comment) => {
      expect(violationsIn("a.ts", comment)).toEqual([
        { line: 1, message: "coverage exclusion in source" },
      ]);
    },
  );

  it.each([
    ["docs/a.md", "Co-Authored-By: Someone <a@example.com>"],
    ["a.ts", "// co-authored-by: someone"],
    ["docs/a.md", "Generated with [Claude Code](https://example.com)"],
    ["docs/a.md", "generated by Claude"],
  ])("[FR-DP-7] rejects attribution in %s: %s", (path, text) => {
    expect(violationsIn(path, text)).toEqual([{ line: 1, message: "attribution line" }]);
  });

  it("[FR-DP-7] skips this package, whose source and tests name every pattern", () => {
    expect(violationsIn("packages/repo-checks/src/a.ts", "const a: any = 1;")).toEqual([]);
  });

  it("[FR-DP-7] reports the file path", () => {
    expect(checkHygiene([{ path: "a.ts", content: "const a: any = 1;" }])).toEqual([
      { path: "a.ts", line: 1, message: "the any type" },
    ]);
  });
});
